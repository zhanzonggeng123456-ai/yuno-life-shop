"""Short-lived role fixtures for isolated native acceptance, never a web route.

Only three exact emails for a numeric run id in data/acceptance-*/yuno.db can
be elevated. Passwords/tokens are generated by the device test, never read here.
Run alongside integration_test/role_flow_test.dart, stop after the test.
"""
import argparse
from pathlib import Path
import sqlite3
import time


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--db', type=Path, required=True)
    parser.add_argument('--run-id', required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    path = args.db.resolve(strict=True)
    relative = path.relative_to(root / 'data')
    if (len(relative.parts) != 2 or not relative.parts[0].startswith('acceptance-')
            or relative.parts[1] != 'yuno.db' or not args.run_id.isdecimal()):
        parser.error('Only a data/acceptance-*/yuno.db and numeric run id are allowed')
    deadline = time.monotonic() + 1200
    while time.monotonic() < deadline:
        with sqlite3.connect(path) as conn:
            for role in ('admin', 'courier', 'appraiser'):
                conn.execute('UPDATE users SET role=? WHERE email=? AND role=?',
                             (role, f'role-acceptance-{args.run_id}-{role}@acceptance.invalid', 'user'))
        time.sleep(.2)


if __name__ == '__main__':
    main()
